
from __future__ import annotations

from typing import Any


def generate_dataset_insights(
    profile: dict[str, Any],
) -> list[dict[str, Any]]:
    """
    Generate deterministic AI-style insights from a dataset profile.

    This version works directly with the profile structure generated by
    profiling_service.profile_dataset().
    """

    insights: list[dict[str, Any]] = []

    columns = profile.get("columns", [])
    correlations = profile.get("correlations", {})
    data_quality = profile.get("data_quality", {})
    overview = profile.get("overview", {})

    # =========================================================
    # 1. DATASET STRUCTURE
    # =========================================================

    row_count = overview.get("row_count", 0)
    column_count = overview.get("column_count", 0)

    if row_count and column_count:
        insights.append(
            {
                "type": "dataset",
                "severity": "info",
                "title": "Dataset structure detected",
                "description": (
                    f"The dataset contains {row_count:,} rows and "
                    f"{column_count:,} columns available for analysis."
                ),
                "recommendation": (
                    "Review column types and data quality before "
                    "building predictive models."
                ),
            }
        )

    # =========================================================
    # 2. MISSING VALUES
    # =========================================================

    missing_columns = [
        column
        for column in columns
        if column.get("missing_count", 0) > 0
    ]

    if missing_columns:
        highest_missing = max(
            missing_columns,
            key=lambda column: column.get(
                "missing_percentage",
                0,
            ),
        )

        missing_percentage = float(
            highest_missing.get(
                "missing_percentage",
                0,
            )
        )

        severity = (
            "high"
            if missing_percentage >= 30
            else "medium"
        )

        insights.append(
            {
                "type": "data_quality",
                "severity": severity,
                "title": "Missing data detected",
                "description": (
                    f"{highest_missing.get('name', 'A column')} "
                    f"has {missing_percentage:.1f}% "
                    f"missing values."
                ),
                "recommendation": (
                    "Investigate why values are missing and "
                    "consider imputation or removing the column "
                    "if appropriate."
                ),
                "column": highest_missing.get("name"),
            }
        )

    else:
        insights.append(
            {
                "type": "data_quality",
                "severity": "success",
                "title": "No missing values detected",
                "description": (
                    "All analyzed columns contain complete values."
                ),
                "recommendation": (
                    "You can proceed to exploratory analysis "
                    "without missing-value preprocessing."
                ),
            }
        )

    # =========================================================
    # 3. DUPLICATE ROWS
    # =========================================================

    duplicate_rows = overview.get(
        "duplicate_rows",
        0,
    )

    if duplicate_rows:
        insights.append(
            {
                "type": "data_quality",
                "severity": "medium",
                "title": "Duplicate records detected",
                "description": (
                    f"The dataset contains approximately "
                    f"{duplicate_rows:,} duplicate rows."
                ),
                "recommendation": (
                    "Review duplicate records before training "
                    "machine learning models to avoid biased results."
                ),
            }
        )

    # =========================================================
    # 4. DATA QUALITY SCORE
    # =========================================================

    quality_score = data_quality.get(
        "quality_score"
    )

    if quality_score is not None:
        quality_score = float(
            quality_score
        )

        if quality_score < 50:
            severity = "high"
        elif quality_score < 80:
            severity = "medium"
        else:
            severity = "success"

        recommendation = (
            "Prioritize data cleaning before advanced modeling."
            if quality_score < 80
            else
            "The dataset has a strong foundation for further analysis."
        )

        insights.append(
            {
                "type": "quality",
                "severity": severity,
                "title": "Data quality assessment",
                "description": (
                    f"The overall data quality score is "
                    f"{quality_score:.1f}/100."
                ),
                "recommendation": recommendation,
            }
        )

    # =========================================================
    # 5. OUTLIERS
    # =========================================================

    outlier_columns = [
        column
        for column in columns
        if column.get("outlier_count", 0) > 0
    ]

    if outlier_columns:
        highest_outliers = max(
            outlier_columns,
            key=lambda column: column.get(
                "outlier_count",
                0,
            ),
        )

        outlier_count = highest_outliers.get(
            "outlier_count",
            0,
        )

        insights.append(
            {
                "type": "outlier",
                "severity": "medium",
                "title": "Potential outliers detected",
                "description": (
                    f"The column "
                    f"'{highest_outliers.get('name', 'unknown')}' "
                    f"contains approximately "
                    f"{outlier_count:,} potential outliers."
                ),
                "recommendation": (
                    "Inspect these observations before deciding "
                    "whether they represent errors or legitimate "
                    "extreme values."
                ),
                "column": highest_outliers.get("name"),
            }
        )

    # =========================================================
    # 6. STRONG CORRELATIONS
    # =========================================================

    strong_correlations: list[dict[str, Any]] = []

    # Your profiling service returns:
    #
    # {
    #     "ColumnA": {
    #         "ColumnB": 0.82,
    #         "ColumnC": 0.31
    #     }
    # }
    #
    # Convert that matrix into individual relationships.

    if isinstance(correlations, dict):

        processed_pairs: set[tuple[str, str]] = set()

        for column_a, related_columns in correlations.items():

            if not isinstance(
                related_columns,
                dict,
            ):
                continue

            for column_b, value in related_columns.items():

                if column_a == column_b:
                    continue

                try:
                    numeric_value = float(value)
                except (
                    TypeError,
                    ValueError,
                ):
                    continue

                pair = tuple(
                    sorted(
                        [
                            str(column_a),
                            str(column_b),
                        ]
                    )
                )

                if pair in processed_pairs:
                    continue

                processed_pairs.add(pair)

                if abs(numeric_value) >= 0.7:
                    strong_correlations.append(
                        {
                            "column_a": str(column_a),
                            "column_b": str(column_b),
                            "correlation": numeric_value,
                        }
                    )

    if strong_correlations:

        strongest = max(
            strong_correlations,
            key=lambda item: abs(
                item["correlation"]
            ),
        )

        correlation_value = float(
            strongest["correlation"]
        )

        direction = (
            "positive"
            if correlation_value > 0
            else "negative"
        )

        insights.append(
            {
                "type": "relationship",
                "severity": "info",
                "title": "Strong relationship detected",
                "description": (
                    f"{strongest['column_a']} and "
                    f"{strongest['column_b']} show a "
                    f"{direction} correlation of "
                    f"{correlation_value:.2f}."
                ),
                "recommendation": (
                    "Investigate this relationship further during "
                    "feature analysis and predictive modeling."
                ),
                "column_a": strongest["column_a"],
                "column_b": strongest["column_b"],
                "correlation": correlation_value,
            }
        )

    # =========================================================
    # 7. LOW-INFORMATION COLUMNS
    # =========================================================

    low_information_columns = []

    for column in columns:

        unique_percentage = column.get(
            "unique_percentage"
        )

        if unique_percentage is None:
            continue

        try:
            unique_percentage = float(
                unique_percentage
            )
        except (
            TypeError,
            ValueError,
        ):
            continue

        if unique_percentage <= 1:
            low_information_columns.append(
                column
            )

    if low_information_columns:

        column_names = [
            column.get(
                "name",
                "unknown",
            )
            for column in low_information_columns[:5]
        ]

        insights.append(
            {
                "type": "feature",
                "severity": "medium",
                "title": "Low-information columns detected",
                "description": (
                    "Some columns contain very few unique values: "
                    + ", ".join(column_names)
                ),
                "recommendation": (
                    "Check whether these columns provide useful "
                    "predictive information before including them "
                    "in a model."
                ),
            }
        )

    # =========================================================
    # 8. FINAL FALLBACK
    # =========================================================

    if not insights:
        insights.append(
            {
                "type": "dataset",
                "severity": "info",
                "title": "No major issues detected",
                "description": (
                    "The current profiling analysis did not identify "
                    "any major data-quality or relationship issues."
                ),
                "recommendation": (
                    "Continue with exploratory analysis or "
                    "predictive modeling."
                ),
            }
        )

    return insights

